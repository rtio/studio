// Writes src/theme/tokens.generated.ts from Studio's design tokens.
//
// Studio computes its colors in CSS (apps/ui/src/lib/theme/tokens.css) with
// color functions that React Native cannot evaluate. This script loads that
// stylesheet in a headless browser, reads each resolved color at Studio's
// default appearance settings, and writes plain hex values.
//
// Run it from apps/mobile with `npm run tokens` after tokens.css changes.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { chromium } from 'playwright';

const appRoot = path.resolve( import.meta.dirname, '..' );
const tokensCssPath = path.resolve( appRoot, '../ui/src/lib/theme/tokens.css' );
const outputPath = path.resolve( appRoot, 'src/theme/tokens.generated.ts' );

// Name in the app, then the CSS custom property it comes from. `surface` is the
// color of the surface itself.
const COLORS = {
	surface: 'surface',
	foreground: 'foreground',
	mutedForeground: 'muted-foreground',
	placeholder: 'placeholder-foreground',
	border: 'border',
	muted: 'muted',
	selected: 'selected',
	primary: 'primary',
	primaryForeground: 'primary-foreground',
	accent: 'accent',
	accentForeground: 'accent-foreground',
	accentText: 'accent-text',
	accentSubtle: 'accent-subtle',
	accentSubtleForeground: 'accent-subtle-foreground',
	success: 'success',
	warning: 'warning',
	destructive: 'destructive',
	destructiveFill: 'destructive-fill',
	destructiveForeground: 'destructive-foreground',
	statusRunning: 'status-running',
	statusTransitioning: 'status-transitioning',
	statusSync: 'status-sync',
};

// Text, borders and fills depend on the surface they sit on, so every color is
// read once per surface. `base` is the page, `floating` is a popover.
const SURFACES = { base: 'background', floating: 'popover' };

const SCHEMES = [ 'light', 'dark' ];

const css = readFileSync( tokensCssPath, 'utf8' );

const browser = await chromium.launch();
let resolved;
try {
	const page = await browser.newPage();
	await page.setContent( '<!doctype html><html><head></head><body></body></html>' );
	await page.addStyleTag( { content: css } );
	resolved = await page.evaluate(
		( { colors, surfaces, schemes } ) => {
			const canvas = document.createElement( 'canvas' );
			canvas.width = 1;
			canvas.height = 1;
			const context = canvas.getContext( '2d', { willReadFrequently: true } );

			// The canvas turns any CSS color into sRGB bytes.
			function toHex( color ) {
				context.clearRect( 0, 0, 1, 1 );
				context.fillStyle = color;
				context.fillRect( 0, 0, 1, 1 );
				const [ red, green, blue, alpha ] = context.getImageData( 0, 0, 1, 1 ).data;
				if ( alpha !== 255 ) {
					throw new Error( `The color ${ color } is not opaque` );
				}
				return (
					'#' +
					[ red, green, blue ].map( ( part ) => part.toString( 16 ).padStart( 2, '0' ) ).join( '' )
				);
			}

			const result = {};
			for ( const scheme of schemes ) {
				result[ scheme ] = {};
				for ( const [ surfaceName, surfaceToken ] of Object.entries( surfaces ) ) {
					const container = document.createElement( 'div' );
					container.setAttribute( 'data-color-scheme', scheme );
					container.style.setProperty( '--surface', `var( --${ surfaceToken } )` );
					const probe = document.createElement( 'span' );
					container.appendChild( probe );
					document.body.appendChild( container );

					const values = {};
					for ( const [ name, token ] of Object.entries( colors ) ) {
						probe.style.color = '';
						probe.style.color = `var( --${ token } )`;
						if ( ! probe.style.color ) {
							throw new Error( `The token --${ token } did not parse` );
						}
						values[ name ] = toHex( getComputedStyle( probe ).color );
					}
					result[ scheme ][ surfaceName ] = values;
					container.remove();
				}
			}
			return result;
		},
		{ colors: COLORS, surfaces: SURFACES, schemes: SCHEMES }
	);
} finally {
	await browser.close();
}

const sourceHash = createHash( 'sha256' ).update( css ).digest( 'hex' );

const lines = [
	'// Generated by scripts/generate-tokens.mjs from apps/ui/src/lib/theme/tokens.css.',
	'// Do not edit. Run `npm run tokens` in apps/mobile after tokens.css changes.',
	'',
	'// The SHA-256 of tokens.css when this file was generated. A test compares it',
	'// with the current file.',
	'export const TOKENS_SOURCE_HASH =',
	`\t'${ sourceHash }';`,
	'',
	'export const tokens = {',
];
for ( const scheme of SCHEMES ) {
	lines.push( `\t${ scheme }: {` );
	for ( const surfaceName of Object.keys( SURFACES ) ) {
		lines.push( `\t\t${ surfaceName }: {` );
		for ( const name of Object.keys( COLORS ) ) {
			lines.push( `\t\t\t${ name }: '${ resolved[ scheme ][ surfaceName ][ name ] }',` );
		}
		lines.push( '\t\t},' );
	}
	lines.push( '\t},' );
}
lines.push( '} as const;', '' );

writeFileSync( outputPath, lines.join( '\n' ) );
console.log( `Wrote ${ path.relative( appRoot, outputPath ) }` );
